"""Явное обучение демонстрационной ML-модели без командной строки."""
import streamlit as st

from model_bootstrap import DEFAULT_DEMO_DATASET, train_demo_model


st.set_page_config(
    page_title="Обучить ML-модель — Anomaly Monitor",
    page_icon="🤖",
    layout="wide",
)

st.title("🤖 Подготовка ML-модели")
st.markdown(
    """
Здесь можно явно обучить демонстрационную модель **Isolation Forest**.
Она изучает только встроенный размеченный набор проекта, где подтверждён
штатный режим **normal**.

**Ваш загруженный CSV в обучение не попадает.** Он остаётся неизвестной пробой,
которую готовая модель только анализирует.
"""
)

st.info(f"Источник обучения: встроенный файл {DEFAULT_DEMO_DATASET.name}.")
st.warning(
    "Это демонстрационная модель для учебного прототипа, а не допущенная "
    "система промышленной безопасности. Решение всегда принимает специалист."
)

if st.button("Обучить демонстрационную ML-модель", type="primary"):
    try:
        with st.spinner("Модель изучает штатный температурный режим..."):
            result = train_demo_model()
    except Exception as error:
        st.error("Не удалось подготовить ML-модель.")
        st.exception(error)
    else:
        info = result["info"]
        report = result["report"]
        st.success(
            "Модель обучена и сохранена. Теперь на главной странице можно "
            "выбрать режим rules+ML."
        )
        col1, col2, col3 = st.columns(3)
        col1.metric("Строк обучения", info["train_rows"])
        col2.metric("Строк независимой проверки", info["evaluation_rows"])
        col3.metric("F1 на проверке", f'{report.get("f1", 0):.4f}')
        st.caption(
            "Созданы scaler.joblib, iforest.joblib и model_meta.json — "
            "единый совместимый комплект модели."
        )

st.markdown(
    """
### Что происходит после нажатия

1. Модель получает только ранние строки с подтверждённым сценарием **normal**.
2. Более поздние строки остаются отдельной проверочной частью.
3. Сохраняются модель, шкала признаков и паспорт совместимости.
4. На главной странице правила и ML смогут работать параллельно.

На облачном хостинге файловая система может очищаться при перезапуске приложения.
В таком случае обучение нужно запустить снова этой же кнопкой.
"""
)
